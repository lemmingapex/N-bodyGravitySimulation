#!/usr/bin/env node
// Copies browser runtime dependencies from node_modules into vendor/ so the site
// can be served as static files (GitHub Pages) without a bundler.
// Run after bumping a vendored package: `npm install && npm run vendor`.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const packages = [
	{
		name: "lil-gui",
		files: [
			["dist/lil-gui.esm.min.js", "lil-gui.esm.min.js"],
			["LICENSE.md", "LICENSE.md"],
		],
		// Lets `tsc` type-check imports of the vendored file using the package's own types.
		typesShim: "lil-gui.esm.min.d.ts",
	},
];

for (const pkg of packages) {
	const src = join(root, "node_modules", pkg.name);
	const dest = join(root, "vendor", pkg.name);
	const { version } = JSON.parse(readFileSync(join(src, "package.json"), "utf8"));
	mkdirSync(dest, { recursive: true });
	for (const [from, to] of pkg.files) {
		copyFileSync(join(src, from), join(dest, to));
	}
	if (pkg.typesShim) {
		writeFileSync(
			join(dest, pkg.typesShim),
			`// Generated by scripts/vendor.js (${pkg.name}@${version}). Do not edit.\n` +
				`export * from "${pkg.name}";\nexport { default } from "${pkg.name}";\n`,
		);
	}
	console.log(`vendored ${pkg.name}@${version} -> vendor/${pkg.name}`);
}
